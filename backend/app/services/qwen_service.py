
import logging
import os
import re
from functools import lru_cache
from pathlib import Path

import torch
from peft import PeftModel
from transformers import (
    AutoModelForCausalLM,
    AutoTokenizer,
    BitsAndBytesConfig,
)

logger = logging.getLogger(__name__)

BASE_MODEL = os.getenv("QWEN_BASE_MODEL", "Qwen/Qwen3-4B")

ADAPTER_DIR = Path(
    os.getenv(
        "QWEN_ADAPTER_PATH",
        str(
            Path(__file__).resolve().parents[2]
            / "models"
            / "qwen3_lora_balanced_4000_v2"
        ),
    )
)


@lru_cache(maxsize=1)
def load_qwen_model():
    if not ADAPTER_DIR.is_dir():
        raise FileNotFoundError(
            f"Qwen adapter directory not found: {ADAPTER_DIR}"
        )

    if not (ADAPTER_DIR / "adapter_config.json").is_file():
        raise FileNotFoundError("adapter_config.json is missing")

    if not (ADAPTER_DIR / "adapter_model.safetensors").is_file():
        raise FileNotFoundError("adapter_model.safetensors is missing")

    if not torch.cuda.is_available():
        raise RuntimeError(
            "Qwen3-4B inference requires a suitable GPU in this configuration. "
            "Use a GPU-hosted inference service."
        )

    quantization_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_compute_dtype=torch.float16,
        bnb_4bit_use_double_quant=True,
    )

    tokenizer = AutoTokenizer.from_pretrained(
        str(ADAPTER_DIR),
        trust_remote_code=True,
    )

    base_model = AutoModelForCausalLM.from_pretrained(
        BASE_MODEL,
        quantization_config=quantization_config,
        device_map="auto",
        trust_remote_code=True,
    )

    model = PeftModel.from_pretrained(base_model, str(ADAPTER_DIR))
    model.eval()

    return tokenizer, model


def predict_with_qwen(features: dict) -> dict:
    tokenizer, model = load_qwen_model()

    # Keep this prompt aligned with the training prompt.
    patient_text = "\n".join(
        f"{key}: {value}"
        for key, value in features.items()
    )

    prompt = (
        "You are a hospital readmission risk classification assistant. "
        "Based only on the patient encounter information below, predict "
        "whether the patient will be readmitted within 30 days. "
        "Return only 1 for readmission within 30 days or 0 otherwise. "
        f"Patient encounter: {patient_text}"
    )

    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)

    with torch.inference_mode():
        output = model.generate(
            **inputs,
            max_new_tokens=5,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id,
        )

    generated = output[0][inputs["input_ids"].shape[1]:]
    answer = tokenizer.decode(
        generated,
        skip_special_tokens=True,
    ).strip()

    match = re.match(r"^\s*([01])\b", answer)
    if not match:
        raise ValueError(
            f"Qwen returned an invalid binary label: {answer!r}"
        )

    prediction = int(match.group(1))

    return {
        "prediction": prediction,
        "risk_label": "positive_screen" if prediction == 1 else "negative_screen",
        "model_name": "Qwen3-4B-LoRA",
        "model_mode": "qwen",
        "readmission_probability": None,
        "confidence": None,
        "readmission_within_30_days": prediction,
        "explanation": [
            "Prediction generated by the trained Qwen3-4B LoRA adapter."
        ],
        "warnings": [
            "Research prototype only; not clinically validated.",
            "The binary output is not a calibrated probability.",
        ],
    }
