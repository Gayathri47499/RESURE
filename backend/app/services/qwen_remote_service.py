
import logging
import os
import re
import uuid
from functools import lru_cache

from gradio_client import Client

logger = logging.getLogger(__name__)

SPACE_ID = "gayathri-sanjana/resure-qwen-inference"


@lru_cache(maxsize=1)
def get_qwen_client():
    token = os.getenv("HF_TOKEN")

    if token:
        return Client(SPACE_ID, hf_token=token)

    return Client(SPACE_ID)


def predict_with_qwen(features: dict) -> dict:
    if not features:
        raise ValueError("Patient encounter features must not be empty.")

    # Send only the feature values required for inference.
    # Do not send patient IDs, encounter IDs, or identifying information.
    patient_text = "\n".join(
        f"{key}: {value}"
        for key, value in features.items()
    )

    try:
        client = get_qwen_client()

        # Exactly one inference call: no automatic retries.
        result = client.predict(
            patient_text=patient_text,
            api_name="/predict_on_gpu",
        )

        match = re.search(
            r"Predicted class:\s*([01])\b",
            str(result),
        )

        if not match:
            raise ValueError(
                "Qwen Space returned no valid prediction. "
                "Check the Space logs and availability."
            )

        label = int(match.group(1))

        return {
            "prediction_id": str(uuid.uuid4()),
            "model_name": "Qwen3-4B-LoRA",
            "model_mode": "qwen",
            "readmission_within_30_days": label,
            "risk_label": (
                "positive_screen" if label == 1 else "negative_screen"
            ),
            "confidence": None,
            "readmission_probability": None,
            "explanation": [
                "Prediction generated by the trained Qwen3-4B LoRA adapter."
            ],
            "warnings": [
                "Research prototype only; not clinically validated.",
                "The predicted class is not a calibrated probability.",
            ],
        }

    except Exception:
        logger.exception("Qwen inference request failed")
        raise
