
import logging
import os
import re
import uuid
from functools import lru_cache

from gradio_client import Client

logger = logging.getLogger(__name__)

SPACE_ID = "gayathri-sanjana/resure-qwen-inference"


@lru_cache(maxsize=1)
def get_qwen_client():
    token = os.getenv("HF_TOKEN")

    if token:
        return Client(SPACE_ID, hf_token=token)

    return Client(SPACE_ID)


def predict_with_qwen(features: dict) -> dict:
    if not features:
        raise ValueError("Patient encounter features must not be empty.")

    # Send model features only. Never send patient identifiers.
    patient_text = "\n".join(
        f"{key}: {value}"
        for key, value in features.items()
    )

    try:
        client = get_qwen_client()

        # One inference call; no automatic retries.
        result = client.predict(
            patient_text=patient_text,
            api_name="/predict_on_gpu",
        )

        response_text = str(result)

        # Extract the predicted class.
        class_match = re.search(
            r"Predicted class:\s*([01])\b",
            response_text,
        )

        if not class_match:
            raise ValueError(
                "Qwen Space returned no valid prediction. "
                "Check the Space output and availability."
            )

        label = int(class_match.group(1))

        # Extract relative next-token scores.
        # These are NOT calibrated clinical probabilities.
        class_0_match = re.search(
            r"Relative Class 0 score:\s*([0-9]+(?:\.[0-9]+)?)%",
            response_text,
        )

        class_1_match = re.search(
            r"Relative Class 1 score:\s*([0-9]+(?:\.[0-9]+)?)%",
            response_text,
        )

        class_0_score = (
            float(class_0_match.group(1)) / 100.0
            if class_0_match
            else None
        )

        class_1_score = (
            float(class_1_match.group(1)) / 100.0
            if class_1_match
            else None
        )

        return {
            "prediction_id": str(uuid.uuid4()),
            "model_name": "Qwen3-4B-LoRA",
            "model_mode": "qwen",
            "readmission_within_30_days": label,
            "risk_label": (
                "positive_screen"
                if label == 1
                else "negative_screen"
            ),
            "confidence": None,
            "readmission_probability": None,
            "relative_class_0_score": class_0_score,
            "relative_class_1_score": class_1_score,
            "explanation": [
                "Prediction generated by the Qwen3-4B LoRA adapter.",
                (
                    "Relative class scores represent next-token "
                    "preferences, not calibrated readmission probabilities."
                ),
            ],
            "warnings": [
                "Research prototype only; not clinically validated.",
                (
                    "Relative class scores must not be interpreted "
                    "as readmission risk percentages."
                ),
            ],
        }

    except Exception:
        logger.exception("Qwen inference request failed")
        raise
